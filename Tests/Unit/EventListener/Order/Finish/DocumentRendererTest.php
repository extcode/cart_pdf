use Extcode\Cart\Domain\Model\Cart\Cart;
use Extcode\Cart\Domain\Model\Order\Item as OrderItem;
use Extcode\Cart\Domain\Repository\Order\ItemRepository as OrderItemRepository;
use Extcode\Cart\Event\Order\FinishEvent;
use Extcode\CartPdf\EventListener\Order\Finish\DocumentRenderer;
use Extcode\CartPdf\Service\DocumentRenderServiceInterface;
use Extcode\CartPdf\Service\FileWriterServiceInterface;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\MockObject\MockObject;
use TYPO3\CMS\Extbase\Persistence\Generic\PersistenceManager;
use TYPO3\TestingFramework\Core\Unit\UnitTestCase;

#[CoversClass(DocumentRenderer::class)]
final class DocumentRendererTest extends UnitTestCase
{
    private PersistenceManager&MockObject $persistenceManager;

    private OrderItemRepository&MockObject $orderItemRepository;

    private DocumentRenderServiceInterface&MockObject $documentRenderService;

    private FileWriterServiceInterface&MockObject $fileWriterService;

    private OrderItem $orderItem;

    private DocumentRenderer $subject;

    protected function setUp(): void
    {
        parent::setUp();

        $this->persistenceManager = $this->createMock(PersistenceManager::class);
        $this->orderItemRepository = $this->createMock(OrderItemRepository::class);
        $this->documentRenderService = $this->createMock(DocumentRenderServiceInterface::class);
        $this->fileWriterService = $this->createMock(FileWriterServiceInterface::class);
        $this->orderItem = new OrderItem();

        $this->subject = new DocumentRenderer(
            $this->persistenceManager,
            $this->orderItemRepository,
            $this->documentRenderService,
            $this->fileWriterService,
        );
    }

    public static function settingsWithoutDocumentsDataProvider(): \Generator
    {
        yield 'no autoGenerateDocuments setting' => [[]];
        yield 'empty autoGenerateDocuments setting' => [['autoGenerateDocuments' => []]];
    }

    #[Test]
    #[DataProvider('settingsWithoutDocumentsDataProvider')]
    public function doesNothingWithoutDocumentsToGenerate(array $settings): void
    {
        $this->documentRenderService->expects(self::never())->method('renderDocument');
        $this->fileWriterService->expects(self::never())->method('writeContentToFile');
        $this->orderItemRepository->expects(self::never())->method('update');
        $this->persistenceManager->expects(self::never())->method('persistAll');

        ($this->subject)($this->createEvent($settings));
    }

    #[Test]
    public function rendersAndWritesEachEnabledDocumentType(): void
    {
        $settings = [
            'autoGenerateDocuments' => [
                'order' => '1',
                'invoice' => '1',
                'delivery' => '0',
            ],
        ];

        $this->documentRenderService
            ->expects(self::exactly(2))
            ->method('renderDocument')
            ->willReturnCallback(
                fn(OrderItem $orderItem, string $documentType): string => 'content of ' . $documentType
            );

        $writtenFiles = [];
        $this->fileWriterService
            ->expects(self::exactly(2))
            ->method('writeContentToFile')
            ->willReturnCallback(
                function (OrderItem $orderItem, string $documentType, string $content) use (&$writtenFiles): void {
                    self::assertSame($this->orderItem, $orderItem);
                    $writtenFiles[$documentType] = $content;
                }
            );

        $this->orderItemRepository->expects(self::once())->method('update');
        $this->persistenceManager->expects(self::once())->method('persistAll');

        ($this->subject)($this->createEvent($settings));

        self::assertSame(
            [
                'order' => 'content of order',
                'invoice' => 'content of invoice',
            ],
            $writtenFiles
        );
    }

    #[Test]
    public function persistsOrderItemOnceAfterAllDocumentsAreWritten(): void
    {
        $settings = [
            'autoGenerateDocuments' => [
                'order' => '1',
                'invoice' => '1',
            ],
        ];

        $calls = [];
        $this->documentRenderService->expects(self::exactly(2))->method('renderDocument')->willReturn('pdf');
        $this->fileWriterService
            ->expects(self::exactly(2))
            ->method('writeContentToFile')
            ->willReturnCallback(function () use (&$calls): void {
                $calls[] = 'write';
            });
        $this->orderItemRepository
            ->expects(self::once())
            ->method('update')
            ->with(self::identicalTo($this->orderItem))
            ->willReturnCallback(function () use (&$calls): void {
                $calls[] = 'update';
            });
        $this->persistenceManager
            ->expects(self::once())
            ->method('persistAll')
            ->willReturnCallback(function () use (&$calls): void {
                $calls[] = 'persistAll';
            });

        ($this->subject)($this->createEvent($settings));

        self::assertSame(['write', 'write', 'update', 'persistAll'], $calls);
    }

    #[Test]
    public function persistsOrderItemEvenIfAllConfiguredDocumentsAreDisabled(): void
    {
        $settings = [
            'autoGenerateDocuments' => [
                'invoice' => '0',
            ],
        ];

        $this->documentRenderService->expects(self::never())->method('renderDocument');
        $this->fileWriterService->expects(self::never())->method('writeContentToFile');
        $this->orderItemRepository->expects(self::once())->method('update');
        $this->persistenceManager->expects(self::once())->method('persistAll');

        ($this->subject)($this->createEvent($settings));
    }

    private function createEvent(array $settings): FinishEvent
    {
        return new FinishEvent(
            self::createStub(Cart::class),
            $this->orderItem,
            $settings
        );
    }
}
